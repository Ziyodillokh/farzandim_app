"""Generate lib/design/icons/g_icons.g.dart — Phosphor Duotone glyphs as SVG path data.

phosphor_flutter 2.1.0 cannot be used directly: its IconData subclass breaks on
Flutter 3.27+ (IconData is a final class). Its font is still the best source of
the duotone glyphs, so this script reads the font from the pub cache and writes
only the icons listed in tool/icons/icons.txt as const path strings on a 256 grid
(the same grid the design canvas uses).

Usage (from farzandim_child/):
    python3 tool/icons/gen_icons.py
Needs: python3 + fontTools (pip install fonttools).
"""
import json
import os
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES_FILE = os.path.join(ROOT, 'tool', 'icons', 'icons.txt')
OUT_FILE = os.path.join(ROOT, 'lib', 'design', 'icons', 'g_icons.g.dart')

# Font: 1024 units per em, ascent 960 → 256 grid with y flipped.
SCALE = 0.25
BASELINE = 240


def phosphor_dir():
    config = json.load(open(os.path.join(ROOT, '.dart_tool', 'package_config.json')))
    for package in config['packages']:
        if package['name'] == 'phosphor_flutter':
            uri = package['rootUri']
            return uri[len('file://'):] if uri.startswith('file://') else os.path.join(ROOT, '.dart_tool', uri)
    sys.exit('phosphor_flutter not found in package_config.json — run flutter pub get')


def codepoints(source):
    """name -> (primary codepoint, secondary codepoint) from phosphor_icons_duotone.dart."""
    pattern = re.compile(
        r'static const (\w+) = PhosphorDuotoneIconData\(\s*0x([0-9a-f]+),\s*PhosphorIconData\(0x([0-9a-f]+)')
    return {m.group(1): (int(m.group(2), 16), int(m.group(3), 16)) for m in pattern.finditer(source)}


def glyph_path(font, cmap, codepoint):
    glyph_set = font.getGlyphSet()
    pen = SVGPathPen(glyph_set, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
    glyph_set[cmap[codepoint]].draw(TransformPen(pen, (SCALE, 0, 0, -SCALE, 0, BASELINE)))
    return pen.getCommands()


def main():
    base = phosphor_dir()
    font = TTFont(os.path.join(base, 'lib', 'fonts', 'Phosphor-Duotone.ttf'))
    cmap = font.getBestCmap()
    points = codepoints(open(os.path.join(base, 'lib', 'src', 'phosphor_icons_duotone.dart')).read())
    names = [n.strip() for n in open(NAMES_FILE) if n.strip() and not n.startswith('#')]
    missing = [n for n in names if n not in points]
    if missing:
        sys.exit(f'unknown icon names: {missing}')

    lines = [
        '// GENERATED by tool/icons/gen_icons.py from Phosphor Duotone (MIT) — do not edit.',
        '// Add a name to tool/icons/icons.txt and re-run the script.',
        '',
        "part of 'g_icon.dart';",
        '',
        '/// Phosphor Duotone glyphs used by the Growth v5 design (256 grid).',
        'abstract final class GIcons {',
    ]
    for name in sorted(set(names)):
        primary, secondary = points[name]
        lines.append(f"  static const {name} = GIconData(")
        lines.append(f"    '{glyph_path(font, cmap, primary)}',")
        lines.append(f"    '{glyph_path(font, cmap, secondary)}',")
        lines.append('  );')
    lines.append('}')
    os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)
    open(OUT_FILE, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(set(names))} icons -> {os.path.relpath(OUT_FILE, ROOT)}')


if __name__ == '__main__':
    main()
